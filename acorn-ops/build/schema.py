"""
Acorn Recyclers Operations Platform - canonical data model.

Every workbook, Word merge token, VBA table constant and piece of documentation is
generated from the definitions in this file. If a field needs to change, change it
here and re-run build_all.py - do not hand-edit the generated .xlsx files.

Column spec: (field_name, kind, width, *, choices=..., formula=..., note=...)

kinds
  text      free text
  memo      long free text (wrapped)
  int       whole number
  num       decimal (2dp)
  money     GBP currency
  kg        kilograms, 0dp
  tonnes    tonnes, 3dp
  pct       percentage stored as a fraction
  date      dd/mm/yyyy
  datetime  dd/mm/yyyy hh:mm
  yn        Yes/No dropdown
  list      dropdown driven by `choices`
  formula   calculated column; `formula` uses {r} for the row number
"""

from dataclasses import dataclass, field
from typing import List, Optional


@dataclass
class Col:
    name: str
    kind: str = "text"
    width: int = 16
    choices: Optional[List[str]] = None
    formula: Optional[str] = None
    note: Optional[str] = None
    required: bool = False


@dataclass
class Table:
    """One Excel Table (ListObject) occupying one worksheet."""
    sheet: str
    table: str
    title: str
    purpose: str
    cols: List[Col]
    sample: List[list] = field(default_factory=list)
    iso: str = ""

    @property
    def key(self) -> str:
        return self.cols[0].name


